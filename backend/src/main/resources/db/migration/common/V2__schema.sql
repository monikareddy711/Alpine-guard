CREATE TABLE station (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    region VARCHAR(80) NOT NULL,
    operator VARCHAR(80) NOT NULL,
    network VARCHAR(40) NOT NULL,
    elevation_m DOUBLE PRECISION NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE station_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id VARCHAR(64) NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    air_temp_c DOUBLE PRECISION,
    wind_speed_ms DOUBLE PRECISION,
    wind_gust_ms DOUBLE PRECISION,
    wind_dir_deg DOUBLE PRECISION,
    snow_depth_cm DOUBLE PRECISION,
    new_snow_cm DOUBLE PRECISION,
    humidity_pct DOUBLE PRECISION,
    pressure_hpa DOUBLE PRECISION,
    CONSTRAINT fk_reading_station FOREIGN KEY (station_id) REFERENCES station (station_id) ON DELETE CASCADE
);

CREATE TABLE ski_route (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    region VARCHAR(80) NOT NULL,
    difficulty VARCHAR(20) NOT NULL,
    distance_m DOUBLE PRECISION NOT NULL,
    ascent_m DOUBLE PRECISION NOT NULL,
    descent_m DOUBLE PRECISION NOT NULL,
    max_elevation_m DOUBLE PRECISION NOT NULL,
    min_elevation_m DOUBLE PRECISION NOT NULL,
    gpx_resource VARCHAR(200) NOT NULL
);

CREATE TABLE route_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL,
    seq INT NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    elevation_m DOUBLE PRECISION NOT NULL,
    distance_m DOUBLE PRECISION NOT NULL,
    slope_deg DOUBLE PRECISION NOT NULL,
    aspect_deg DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_point_route FOREIGN KEY (route_id) REFERENCES ski_route (id) ON DELETE CASCADE
);

CREATE TABLE bulletin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region VARCHAR(80) NOT NULL,
    valid_date DATE NOT NULL,
    elevation_band VARCHAR(20) NOT NULL,
    danger_rating INT NOT NULL,
    main_problem VARCHAR(60),
    summary VARCHAR(600),
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL
);
